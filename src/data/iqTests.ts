export type IqAgeGroup = 'kids' | 'juniors' | 'adults';

export type IqPuzzleKind = 'matrix' | 'odd' | 'sequence' | 'spatial' | 'logic';

export type IqCognitiveDomain = 'pattern' | 'logic' | 'numerical' | 'spatial';

export type GlyphColor = '#0c4a6e' | '#047857' | '#b45309' | '#be123c' | '#334155';

export interface VisualGlyph {
  shape?: 'circle' | 'square' | 'triangle' | 'diamond' | 'star' | 'hexagon' | 'arrow';
  fill?: 'solid' | 'outline' | 'striped';
  color?: GlyphColor;
  count?: 1 | 2 | 3 | 4 | 5;
  rotation?: number; // degrees
  innerDots?: number; // 1..4 dots inside shape
  gridDots?: number[]; // indices 0..8 on a 3x3 lattice
  clock?: { hour: number; minute: number };
  label?: string; // optional number or short symbol
}

export interface IqOption {
  labelAr?: string;
  labelEn?: string;
  glyph?: VisualGlyph;
}

export interface IqQuestion {
  id: string;
  ageGroup: IqAgeGroup;
  kind: IqPuzzleKind;
  domain: IqCognitiveDomain;
  titleAr: string;
  titleEn: string;
  hintAr: string;
  hintEn: string;
  /** For 'matrix': 4 cells (2x2) or 9 cells (3x3) where last cell is null (`?`) */
  matrixCells?: (VisualGlyph | null)[];
  matrixCols?: 2 | 3;
  /** For 'sequence': sequence steps followed by `?` */
  sequenceItems?: VisualGlyph[];
  /** For 'spatial': reference visual target on left/top */
  targetGlyph?: VisualGlyph;
  /** 4 answer choices */
  options: [IqOption, IqOption, IqOption, IqOption];
  correctIndex: 0 | 1 | 2 | 3;
  explanationAr: string;
  explanationEn: string;
}

